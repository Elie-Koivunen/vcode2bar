#!/usr/bin/env python3
"""Generate the web version's shared data from the Python version, so both stay in step.

    python web/tools/gen_fixtures.py          (run from the repository root, needs python-barcode)

Writes
  web/js/strings-core.js   all UI strings of vcode2bar.py (T) in en/fi/sv/nb, unchanged
  web/js/code128-table.js  python-barcode's Code 128 module patterns (the encoder's lookup table)
  web/tests/vectors.json   expected results computed by vcode2bar.py: official + third-party test
                           invoices, 300 random codes with their exact bar patterns, invalid codes,
                           code building from fields, reference helpers, amount/date parsing,
                           text extraction, CSV export and batch-CSV import

The web test page (web/tests/) checks the JavaScript against these vectors, so any difference between
the browser version and the Python version shows up as a failing test.
"""
from __future__ import annotations

import io
import json
import random
import sys
import tempfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import vcode2bar as v  # noqa: E402
from barcode import Code128  # noqa: E402
from barcode.charsets import code128 as c128  # noqa: E402

WEB = ROOT / "web"
HEADER = "// GENERATED by web/tools/gen_fixtures.py from vcode2bar.py - do not edit by hand.\n"


def modules(code: str) -> str:
    """The exact bar/space pattern python-barcode renders (1 = bar module, 0 = space)."""
    return Code128(code).build()[0]


def fields(vb) -> dict:
    return {"version": vb.version, "iban": vb.iban, "cents": int(vb.amount * 100),
            "reference": vb.reference, "due": vb.due_date.isoformat() if vb.due_date else None}


def err_of(fn, *args):
    try:
        fn(*args)
    except v.FieldError as e:
        return {"field": e.field, "message": str(e)}
    except v.VirtualBarcodeError as e:
        return {"field": "code", "message": str(e)}
    return None


def main() -> None:
    rng = random.Random(20261011)
    out: dict = {"generated_from": f"vcode2bar {v.__version__}"}

    # --- valid codes: official, third party, random
    def entry(code, source):
        vb = v.parse(code)
        return {"source": source, "code": code, **fields(vb), "modules": modules(code),
                "checksum": v.code128c_checksum(code)}
    valid = [entry(p.replace(" ", ""), f"official {i + 1}") for i, (p, *_rest) in enumerate(v.OFFICIAL)]
    valid += [entry(c, f"third party {i + 1}") for i, (c, *_r) in enumerate(v.THIRD_PARTY)]
    valid += [entry(v.random_case(rng)[0], "random") for _ in range(300)]
    out["valid"] = valid
    out["official_printed_checksums"] = [chk for *_x, chk in v.OFFICIAL]

    # --- invalid codes (Python's NEGATIVE set + extra shapes)
    neg = dict(v.NEGATIVE)
    neg.update({"empty": "", "spaces only": "   ", "55 digits": valid[0]["code"] + "1",
                "version 6": "6" + valid[0]["code"][1:]})
    out["invalid"] = [{"name": k, "code": c, "message": err_of(v.parse, c)["message"]} for k, c in neg.items()]
    out["spaced"] = [{"input": " ".join(c[i:i + 4] for i in range(0, 54, 4)).replace(" ", "-", 3), "code": c}
                     for c in (valid[0]["code"], valid[9]["code"])]

    # --- building codes from fields (inverse of parse), in many input styles
    build = []
    for pairs, iban, amt, ref, due, _chk in v.OFFICIAL:
        code = pairs.replace(" ", "")
        for style in range(3):
            ib = [iban, " ".join(iban[i:i + 4] for i in range(0, 18, 4)), iban.lower()][style]
            a = [amt, amt.replace(".", ","), v.fmt_amount(v.parse(code), "en").replace(" €", " €")][style]
            if v.parse(code).amount == 0:
                a = ["", "0", "0,00"][style]
            r = [ref, " ".join(ref[i:i + 4] for i in range(0, len(ref), 4)), ref.lower()][style]
            # two-digit years follow strptime: 69-99 mean 19xx, so use them only up to 2068
            short = due.strftime("%d.%m.%y") if due and due.year < 2069 else (due.strftime("%d/%m/%Y") if due else "")
            d = "" if due is None else [due.strftime("%d.%m.%Y"), due.isoformat(), short][style]
            assert v.build_code(ib, a, r, d) == code
            build.append({"iban": ib, "amount": a, "reference": r, "due": d, "code": code})
    for _ in range(150):
        code, iban, amt, ref, due = v.random_case(rng)
        build.append({"iban": iban, "amount": str(amt), "reference": ref,
                      "due": due.isoformat() if due else "", "code": code})
    out["build"] = build
    good = dict(iban="FI7944052020036082", amount="50", reference="868516259619897", due="08.09.2026")
    bad = [("iban", "FI7944052020036083"), ("iban", "SE4550000000058398257466"), ("iban", "FI79"), ("iban", ""),
           ("amount", "1000000"), ("amount", "12,345"), ("amount", "-5"), ("amount", "abc"),
           ("reference", "868516259619898"), ("reference", "123"), ("reference", "RF18ABC123"),
           ("reference", "RF00123"), ("reference", "1" * 21), ("reference", ""),
           ("due", "31.02.2026"), ("due", "01.01.1999"), ("due", "tomorrow")]
    out["build_errors"] = []
    for fld, val in bad:
        kw = dict(good, **{fld: val})
        e = err_of(v.build_code, kw["iban"], kw["amount"], kw["reference"], kw["due"])
        assert e and e["field"] == fld, (fld, val, e)
        out["build_errors"].append({**kw, "field": fld})

    # --- helpers and parsers
    out["fi_reference"] = [{"base": b, "ref": v.fi_reference(b)} for b in
                           ["4090", "123", "1234567890123456789"] + [str(rng.randint(100, 10**19 - 1)) for _ in range(30)]]
    out["fi_reference_errors"] = ["12", "", "abc", "1" * 20]
    out["rf_reference"] = [{"body": b, "ref": v.rf_reference(b)} for b in
                           ["40905", "868516259619897"] + [v.fi_reference(str(rng.randint(100, 10**19 - 1))) for _ in range(30)]]
    amounts = ["1 234,56", "1.234,56", "1,234.56", "12,5 €", "EUR 7", "", "999999,99", "0,05", "7", "10.10", "1 000,00"]
    out["amounts"] = [{"text": t, "cents": int(v.parse_amount(t) * 100)} for t in amounts]
    out["amount_errors"] = ["1000000", "12,345", "-5", "abc", "1,2,3", "5."]
    dues = ["08.09.2026", "2026-09-08", "8.9.2026", "08.09.26", "08/09/2026", "", " 1.1.2000 ", "31.12.68"]
    out["dues"] = [{"text": t, "due": (lambda d: d.isoformat() if d else None)(v.parse_due(t))} for t in dues]
    out["due_errors"] = ["31.02.2026", "01.01.1999", "tomorrow", "2026-13-01", "24.12.99", "01.01.69", "29.02.2027"]
    for t in out["due_errors"]:
        assert err_of(v.parse_due, t), t

    # --- finding codes in text
    c0, c9 = valid[0]["code"], valid[9]["code"]
    g = " ".join(c0[i:i + 4] for i in range(0, 54, 4))
    texts = [f"{pre}{g} 12 kiitos" for pre in ("Summa 45 ", "Asiakas 4 ", "Rivi 5 - ", "4 5 4 5 ", "Tel 0401234567\n")]
    texts += [f"A: {c0} B: {c9} A again {c0}", "nothing here 123", f"Lasku\nViivakoodi: {'-'.join(c9[i:i+6] for i in range(0, 54, 6))}\n"]
    out["extract"] = [{"text": t, "codes": [x.raw for x in v.iter_codes(t)]} for t in texts]

    # --- CSV export (decoded_at is a timestamp and is left out of the comparison)
    recs = [v.to_record(v.parse(e["code"]), s, today=date(2026, 10, 11)) for e, s in
            zip(valid[:5], ["src0", "=HYPERLINK(\"x\")", "Sähkö; lasku", "a,b", "+1"])]
    for r in recs:                                       # fixed timestamp: the output must be reproducible
        r["decoded_at"] = "2026-10-11T12:00:00"
    with tempfile.TemporaryDirectory() as t:
        res = {}
        for excel in (False, True):
            p = v.write_csv(recs, Path(t) / "x.csv", excel_fi=excel)
            res["excel" if excel else "standard"] = p.read_bytes().decode("utf-8-sig")
    out["csv_export"] = {"today": "2026-10-11", "rows": [{k: r[k] for k in v.CSV_FIELDS} for r in recs], **res}

    # --- batch CSV import: Python's verdict on each sample file
    samples = {
        "english.csv": ("invoice,iban,amount,reference,due,notes\n"
                        "A-1,FI79 4405 2020 0360 82,4883.15,868516259619897,2010-06-12,rent\n\n"
                        'A-2,FI58 1017 1000 0001 22,"482,99",RF06 5595 8224 3294 671,31.01.2010,\n'
                        "A-3,FI7944052020036082,12.345,868516259619897,,bad amount\n"
                        "A-4,FI7944052020036082,1,868516259619898,,bad reference\n"
                        "A-5,FI7944052020036082,1,868516259619897,31.02.2026,bad date\n"
                        "A-6,,,,,no account\n").encode("utf-8"),
        "finnish_excel.csv": ("Tili;Summa;Viite;Eräpäivä\r\nFI02 5000 4640 0013 02;693,80;69875 67208 34353 64;24.7.2011\r\n").encode("utf-8-sig"),
        "swedish_cp1252.csv": ("Konto;Belopp;Referens;Förfallodag\r\nFI0250004640001302;693,80;69875672083435364;24.07.2011\r\n").encode("cp1252"),
        "norwegian_tab.csv": ("Konto\tBeløp\tReferanse\tForfallsdato\nFI0250004640001302\t693,80\t69875672083435364\t2011-07-24\n").encode("cp1252"),
        "codes.csv": ("source,code\nfirst," + c0 + "\nsecond,=\"" + c9 + "\"\nbroken,123\n").encode("utf-8"),
        "quoted_multiline.csv": ('name,iban,amount,reference\n"Two\nline name",FI7944052020036082,"1,00",868516259619897\n').encode("utf-8"),
    }
    with tempfile.TemporaryDirectory() as t:
        bat = []
        for name, data in samples.items():
            p = Path(t) / name
            p.write_bytes(data)
            rows = [{"line": r.line, "source": r.source, "code": r.vb.raw if r.vb else None, "field": r.field or None}
                    for r in v.read_batch_csv(p)]
            bat.append({"name": name, "bytes_b64": __import__("base64").b64encode(data).decode(), "rows": rows})
        for name, data in {"empty.csv": b"", "other.csv": b"foo,bar\n1,2\n", "half.csv": b"iban,amount\nFI7944052020036082,5\n"}.items():
            p = Path(t) / name
            p.write_bytes(data)
            bat.append({"name": name, "bytes_b64": __import__("base64").b64encode(data).decode(),
                        "error": err_of(v.read_batch_csv, p)["message"]})
    out["batch"] = bat
    out["batch_columns"] = {k: list(names) for k, names in v.BATCH_COLUMNS.items()}

    # --- display formatting
    out["format"] = [{"code": e["code"], "iban": v.fmt_iban(v.parse(e["code"]).iban),
                      "amount": {lang: v.fmt_amount(v.parse(e["code"]), lang) for lang in v.T},
                      "reference": v.fmt_ref(v.parse(e["code"]))} for e in valid[:20]]

    # --- image / PDF files made by the Python version, for the browser reader to read back
    from PIL import Image
    from barcode.writer import ImageWriter
    fx = WEB / "tests" / "fixtures"
    fx.mkdir(parents=True, exist_ok=True)
    a, b = v.render_image(v.parse(c0)).convert("L"), v.render_image(v.parse(c9)).convert("L")
    files = []
    a.rotate(90, expand=True).save(fx / "py_rot90.jpg", quality=60)
    files.append({"file": "py_rot90.jpg", "codes": [c0]})
    a.rotate(-12, expand=True, fillcolor=255, resample=Image.BICUBIC).resize((a.width // 3, a.height // 3)) \
        .save(fx / "py_tilt_small.png")
    files.append({"file": "py_tilt_small.png", "codes": [c0]})
    both = Image.new("L", (a.width, a.height + b.height + 200), 255)
    both.paste(a, (0, 0)); both.paste(b, (0, a.height + 200))
    both.save(fx / "py_two.png")
    files.append({"file": "py_two.png", "codes": sorted([c0, c9])})
    Code128("INVOICE-2024-0042", writer=ImageWriter()).render().save(fx / "py_nonbank.png")
    files.append({"file": "py_nonbank.png", "codes": [], "rejected_contains": "INVOICE"})
    Image.new("RGB", (800, 300), "white").save(fx / "py_blank.png")
    files.append({"file": "py_blank.png", "codes": [], "error": "no barcode found"})
    b.convert("RGB").save(fx / "py_image_only.pdf", "PDF", resolution=600)
    files.append({"file": "py_image_only.pdf", "codes": [c9]})
    v._mini_pdf(fx / "py_text_only.pdf", ["Lasku 1043", "Puh 040 1234567", "Virtuaaliviivakoodi:", g])
    files.append({"file": "py_text_only.pdf", "codes": [c0]})
    v._mini_pdf(fx / "py_nothing.pdf", ["Nothing to pay here", "Tel 0401234567"])
    files.append({"file": "py_nothing.pdf", "codes": [], "error_any": True})
    (fx / "not_an_image.png").write_bytes(b"\x89PNG garbage")
    files.append({"file": "not_an_image.png", "codes": [], "error_any": True})
    for f in files:                                     # the Python reader agrees with every fixture
        r = v.read_file(fx / f["file"])
        assert sorted(x.raw for x in r.codes) == sorted(f["codes"]), (f, r.summary())
    out["files"] = files

    (WEB / "tests").mkdir(parents=True, exist_ok=True)
    (WEB / "js").mkdir(parents=True, exist_ok=True)
    (WEB / "tests" / "vectors.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    strings = {lang: {k: (val if not isinstance(val, list) else [list(x) for x in val]) for k, val in d.items()}
               for lang, d in v.T.items()}
    (WEB / "js" / "strings-core.js").write_text(
        HEADER + "// UI strings of the Python version (vcode2bar.T), shared by the web version.\n"
        f"// Source: vcode2bar {v.__version__}\n"
        "window.VC_STRINGS_CORE = " + json.dumps(strings, ensure_ascii=False, indent=1) + ";\n"
        "window.VC_LANGUAGES = " + json.dumps(v.LANGUAGES, ensure_ascii=False) + ";\n"
        f"window.VC_VERSION = {json.dumps(v.__version__)};   // one version for both editions\n",
        encoding="utf-8")

    codes = list(c128.CODES)
    assert len(codes) >= 106, len(codes)
    stop = c128.STOP + "11"          # python-barcode appends the 2-module termination bar after STOP
    assert modules(c0).endswith(stop) and len(stop) == 13
    (WEB / "js" / "code128-table.js").write_text(
        HEADER + "// Code 128 module patterns, index = symbol value 0..105 (1 = bar, 0 = space), plus the\n"
        "// 13-module stop pattern (STOP + termination bar).\n"
        "// Source: python-barcode (barcode/charsets/code128.py), the encoder the Python version uses.\n"
        "window.VC_CODE128 = " + json.dumps({"codes": codes[:106], "stop": stop}, indent=0) + ";\n",
        encoding="utf-8")
    print(f"wrote vectors ({len(valid)} valid codes), strings ({len(v.T)} languages), Code 128 table")


if __name__ == "__main__":
    main()
